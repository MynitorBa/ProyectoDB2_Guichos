CREATE TABLE IF NOT EXISTS alertas_fraude (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  huella VARCHAR(64) NOT NULL,
  tipo VARCHAR(60) NOT NULL,
  prioridad ENUM('informativa','baja','media','alta') NOT NULL DEFAULT 'baja',
  estado ENUM('pendiente','en_revision','descartada','revisada') NOT NULL DEFAULT 'pendiente',
  usuario_id INT UNSIGNED NULL,
  vendedor_id INT UNSIGNED NULL,
  producto_ref CHAR(24) NULL,
  oferta_id INT UNSIGNED NULL,
  motivos JSON NOT NULL,
  evidencias JSON NOT NULL,
  primera_deteccion DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ultima_deteccion DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  revisada_por INT UNSIGNED NULL,
  notas_revision TEXT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_alerta_fraude_huella (huella),
  KEY ix_alerta_estado_prioridad (estado, prioridad, ultima_deteccion),
  CONSTRAINT fk_alerta_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios(id),
  CONSTRAINT fk_alerta_vendedor FOREIGN KEY (vendedor_id) REFERENCES vendedores(id),
  CONSTRAINT fk_alerta_oferta FOREIGN KEY (oferta_id) REFERENCES ofertas(id),
  CONSTRAINT fk_alerta_revisor FOREIGN KEY (revisada_por) REFERENCES usuarios(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
